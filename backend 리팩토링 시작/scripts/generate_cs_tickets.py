CATEGORY_COUNTS = {
    "배송": 73,
    "환불": 38,
    "결제": 47,
    "상품": 56,
    "계정": 37,
    "정산": 20,
    "기술지원": 106,
    "마케팅": 46,
    "기타": 80,
}

SELLER_TIERS = ["Basic", "Standard", "Premium", "Enterprise"]
TIER_WEIGHTS = [0.4, 0.3, 0.2, 0.1]


def generate():
    base_date = datetime(2025, 1, 1)
    rows = []
    ticket_num = 1

    for category, total_count in CATEGORY_COUNTS.items():
        topics = TOPIC_VARIANTS[category]
        topic_names = list(topics.keys())

        # 주제별 가중치: 앞쪽 주제가 더 빈출 (지프 법칙 느낌)
        weights = [max(len(topic_names) - i, 1) for i in range(len(topic_names))]
        total_w = sum(weights)
        topic_counts = {}
        remaining = total_count
        for i, name in enumerate(topic_names):
            if i == len(topic_names) - 1:
                topic_counts[name] = remaining
            else:
                cnt = round(total_count * weights[i] / total_w)
                cnt = max(cnt, 2)
                topic_counts[name] = cnt
                remaining -= cnt

        for topic_name, cnt in topic_counts.items():
            variants = topics[topic_name]
            for _ in range(cnt):
                text = random.choice(variants)
                tier = random.choices(SELLER_TIERS, weights=TIER_WEIGHTS, k=1)[0]
                days_offset = random.randint(0, 364)
                created = base_date + timedelta(
                    days=days_offset,
                    hours=random.randint(8, 22),
                    minutes=random.randint(0, 59),
                )
                rows.append({
                    "ticket_id": f"T{ticket_num:04d}",
                    "category": category,
                    "inquiry_text": text,
                    "seller_tier": tier,
                    "created_at": created.strftime("%Y-%m-%d %H:%M:%S"),
                })
                ticket_num += 1

    random.shuffle(rows)

    out_path = os.path.join(os.path.dirname(os.path.dirname(__file__)), "cs_tickets.csv")
    with open(out_path, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["ticket_id", "category", "inquiry_text", "seller_tier", "created_at"])
        writer.writeheader()
        writer.writerows(rows)

    print(f"generated: {out_path}")
    print(f"total {len(rows)} tickets")
    for cat, cnt in CATEGORY_COUNTS.items():
        topics = TOPIC_VARIANTS[cat]
        print(f"  {cat}: {cnt} tickets, {len(topics)} topic groups")


if __name__ == "__main__":
    generate()
